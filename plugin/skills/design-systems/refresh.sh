#!/bin/bash
# Fetch Open Design's design systems (English-only) into a folder outside the plugin.
# Usage: refresh.sh [destination]   (default: ~/.claude/starter-kit/design-systems)
# Pinned to one tested upstream commit so everyone on a kit version gets the same set.
# Safe to re-run: it rebuilds systems/ and CATALOG.md from scratch.
set -euo pipefail

OD_COMMIT=26d60298f8129e229a1c10aab4df7ca25b1e9ad3
OD_REPO=https://github.com/nexu-io/open-design.git
DEST="${1:-$HOME/.claude/starter-kit/design-systems}"
KEEP="DESIGN.md USAGE.md tokens.css tailwind-v4.css components.html components.manifest.json design-tokens.json"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
echo "Fetching Open Design at ${OD_COMMIT:0:7}…"
git -C "$TMP" init -q od
git -C "$TMP/od" remote add origin "$OD_REPO"
git -C "$TMP/od" fetch -q --depth 1 origin "$OD_COMMIT"
git -C "$TMP/od" checkout -q FETCH_HEAD

SRC="$TMP/od/design-systems"
mkdir -p "$DEST"
rm -rf "$DEST/systems"
mkdir -p "$DEST/systems"

CATALOG="$DEST/CATALOG.md"
printf '# Design systems catalog\n\nGenerated by refresh.sh from Open Design %s. One folder per system under systems/.\n\n' "${OD_COMMIT:0:7}" > "$CATALOG"

count=0
for d in "$SRC"/*/; do
  name="$(basename "$d")"
  [ "$name" = "_schema" ] && continue
  mkdir -p "$DEST/systems/$name"
  for f in $KEEP; do
    if [ -f "$d/$f" ]; then cp -f "$d/$f" "$DEST/systems/$name/$f"; fi
  done
  # Descriptor = first markdown H1 in DESIGN.md, else the folder name.
  desc="$(grep -m1 '^# ' "$DEST/systems/$name/DESIGN.md" 2>/dev/null | sed 's/^# *//' || true)"
  [ -z "$desc" ] && desc="$name"
  printf -- '- **%s** — %s\n' "$name" "$desc" >> "$CATALOG"
  count=$((count+1))
done

cp -f "$SRC/README.md" "$DEST/ATTRIBUTION.md" 2>/dev/null || true
echo "Vendored $count systems into $DEST/systems"
